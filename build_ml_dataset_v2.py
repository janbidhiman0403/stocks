"""
AlphaLens V2 ML Dataset Builder

Combines:
    1. Existing technical + news features
    2. V2 target definitions

Creates:
    data/ml_ready_TCS_v2.csv

Design goals:
    - Date-aligned
    - Chronological
    - No target columns used as features
    - No accidental duplicate dates
    - No missing feature values
    - Suitable for walk-forward ML experiments
"""

import os
import sys
import pandas as pd
import numpy as np


# ============================================================
# CONFIGURATION
# ============================================================

FEATURE_FILE = r"data\ml_ready_TCS_news_clean.csv"
TARGET_FILE = r"data\ml_targets_v2.csv"
OUTPUT_FILE = r"data\ml_ready_TCS_v2.csv"

DATE_COL = "Date"

# Target columns generated by create_ml_targets_v2.py
TARGET_COLUMNS = [
    "Target_Return_1D",
    "Target_Return_5D",
    "Target_Return_10D",
    "Target_Direction_1D",
    "Target_Direction_5D",
    "Target_Regime_1D",
    "Target_Volatility_20",
]

# Columns that should NEVER become ML features
PROTECTED_COLUMNS = TARGET_COLUMNS.copy()


# ============================================================
# HELPERS
# ============================================================

def fail(message):
    print("\n" + "=" * 70)
    print("ERROR")
    print("=" * 70)
    print(message)
    print("=" * 70)
    sys.exit(1)


def print_section(title):
    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)


# ============================================================
# START
# ============================================================

print("=" * 70)
print("ALPHALENS V2 ML DATASET BUILDER")
print("=" * 70)

print(f"\nFeatures : {FEATURE_FILE}")
print(f"Targets  : {TARGET_FILE}")
print(f"Output   : {OUTPUT_FILE}")


# ============================================================
# 1. CHECK FILES
# ============================================================

print_section("1. FILE VALIDATION")

if not os.path.exists(FEATURE_FILE):
    fail(f"Feature file not found:\n{FEATURE_FILE}")

if not os.path.exists(TARGET_FILE):
    fail(f"Target file not found:\n{TARGET_FILE}")

print("Feature file: FOUND")
print("Target file : FOUND")


# ============================================================
# 2. LOAD DATA
# ============================================================

print_section("2. LOADING DATA")

features = pd.read_csv(FEATURE_FILE)
targets = pd.read_csv(TARGET_FILE)

print(f"Feature rows   : {len(features)}")
print(f"Feature columns: {len(features.columns)}")

print(f"Target rows    : {len(targets)}")
print(f"Target columns : {len(targets.columns)}")


# ============================================================
# 3. DATE VALIDATION
# ============================================================

print_section("3. DATE VALIDATION")

if DATE_COL not in features.columns:
    fail(f"'{DATE_COL}' missing from feature dataset.")

if DATE_COL not in targets.columns:
    fail(f"'{DATE_COL}' missing from target dataset.")

features[DATE_COL] = pd.to_datetime(
    features[DATE_COL],
    errors="coerce"
)

targets[DATE_COL] = pd.to_datetime(
    targets[DATE_COL],
    errors="coerce"
)

if features[DATE_COL].isna().any():
    fail("Feature dataset contains invalid dates.")

if targets[DATE_COL].isna().any():
    fail("Target dataset contains invalid dates.")

features = features.sort_values(DATE_COL).reset_index(drop=True)
targets = targets.sort_values(DATE_COL).reset_index(drop=True)

print(
    "Feature date range:",
    features[DATE_COL].min().date(),
    "to",
    features[DATE_COL].max().date()
)

print(
    "Target date range :",
    targets[DATE_COL].min().date(),
    "to",
    targets[DATE_COL].max().date()
)


# ============================================================
# 4. DUPLICATE DATE CHECK
# ============================================================

print_section("4. DUPLICATE DATE CHECK")

feature_duplicates = features[DATE_COL].duplicated().sum()
target_duplicates = targets[DATE_COL].duplicated().sum()

print(f"Feature duplicate dates: {feature_duplicates}")
print(f"Target duplicate dates : {target_duplicates}")

if feature_duplicates > 0:
    fail("Feature dataset contains duplicate dates.")

if target_duplicates > 0:
    fail("Target dataset contains duplicate dates.")

print("PASS: No duplicate dates.")


# ============================================================
# 5. TARGET COLUMN VALIDATION
# ============================================================

print_section("5. TARGET COLUMN VALIDATION")

missing_targets = [
    col for col in TARGET_COLUMNS
    if col not in targets.columns
]

if missing_targets:
    fail(
        "The following target columns are missing:\n"
        + "\n".join(f" - {x}" for x in missing_targets)
    )

print("All V2 target columns found:")

for col in TARGET_COLUMNS:
    print(f" - {col}")


# ============================================================
# 6. PREVENT TARGET DUPLICATION
# ============================================================

print_section("6. PRE-MERGE COLUMN CHECK")

# Remove any old target columns from feature dataset.
# This protects against accidentally carrying old targets
# into the feature matrix.

old_targets_in_features = [
    col for col in PROTECTED_COLUMNS
    if col in features.columns
]

if old_targets_in_features:
    print("Removing target columns already present in feature dataset:")

    for col in old_targets_in_features:
        print(f" - {col}")

    features = features.drop(
        columns=old_targets_in_features
    )

else:
    print("No V2 target columns found in feature dataset.")

# Also remove any duplicate non-Date columns from target file
# that are already represented in features.
target_keep = [DATE_COL] + TARGET_COLUMNS

targets = targets[target_keep]


# ============================================================
# 7. MERGE
# ============================================================

print_section("7. DATE-ALIGNED MERGE")

merged = pd.merge(
    features,
    targets,
    on=DATE_COL,
    how="inner",
    validate="one_to_one"
)

print(f"Rows after merge: {len(merged)}")
print(f"Columns          : {len(merged.columns)}")

if len(merged) == 0:
    fail("Merge produced zero rows.")

print("PASS: One-to-one date alignment.")


# ============================================================
# 8. SORT CHRONOLOGICALLY
# ============================================================

merged = (
    merged
    .sort_values(DATE_COL)
    .reset_index(drop=True)
)

print_section("8. CHRONOLOGICAL VALIDATION")

is_sorted = merged[DATE_COL].is_monotonic_increasing
duplicates_after_merge = merged[DATE_COL].duplicated().sum()

print(f"Dates sorted          : {is_sorted}")
print(f"Duplicate dates       : {duplicates_after_merge}")

if not is_sorted:
    fail("Merged dataset is not chronological.")

if duplicates_after_merge > 0:
    fail("Merged dataset contains duplicate dates.")

print("PASS: Chronological dataset.")


# ============================================================
# 9. REMOVE ROWS WITH MISSING TARGETS
# ============================================================

print_section("9. TARGET VALIDATION")

before_target_drop = len(merged)

target_missing = merged[TARGET_COLUMNS].isna().sum()

print("Missing target values:")

for col, count in target_missing.items():
    print(f"{col:25s}: {count}")

merged = merged.dropna(
    subset=TARGET_COLUMNS
).reset_index(drop=True)

removed_target_rows = (
    before_target_drop - len(merged)
)

print(f"\nRows removed: {removed_target_rows}")
print(f"Rows remaining: {len(merged)}")


# ============================================================
# 10. FEATURE IDENTIFICATION
# ============================================================

feature_columns = [
    col
    for col in merged.columns
    if col not in PROTECTED_COLUMNS
    and col != DATE_COL
]

print_section("10. FEATURE SET")

print(f"Feature count: {len(feature_columns)}")
print(f"Target count : {len(TARGET_COLUMNS)}")

print("\nFeatures:")

for i, col in enumerate(feature_columns, start=1):
    print(f"{i:02d}. {col}")


# ============================================================
# 11. NUMERIC FEATURE VALIDATION
# ============================================================

print_section("11. FEATURE VALIDATION")

non_numeric_features = []

for col in feature_columns:
    if not pd.api.types.is_numeric_dtype(
        merged[col]
    ):
        non_numeric_features.append(col)

if non_numeric_features:
    print("WARNING: Non-numeric features detected:")

    for col in non_numeric_features:
        print(f" - {col}")

    fail(
        "All ML features must be numeric. "
        "Convert categorical/text features before training."
    )

print("PASS: All features are numeric.")


# ============================================================
# 12. MISSING FEATURE VALUES
# ============================================================

print_section("12. MISSING FEATURE CHECK")

feature_missing = merged[feature_columns].isna().sum()

total_missing_features = feature_missing.sum()

print(
    f"Total missing feature values: "
    f"{total_missing_features}"
)

if total_missing_features > 0:

    print("\nMissing values by feature:")

    for col, count in feature_missing[
        feature_missing > 0
    ].items():
        print(f" - {col}: {count}")

    fail(
        "Missing feature values detected. "
        "Do not train until these are handled."
    )

print("PASS: No missing feature values.")


# ============================================================
# 13. INFINITE VALUE CHECK
# ============================================================

print_section("13. INFINITE VALUE CHECK")

numeric_features = merged[feature_columns]

infinite_mask = np.isinf(
    numeric_features.to_numpy()
)

infinite_count = infinite_mask.sum()

print(f"Infinite feature values: {infinite_count}")

if infinite_count > 0:
    fail(
        "Infinite values detected in features."
    )

print("PASS: No infinite feature values.")


# ============================================================
# 14. TARGET DISTRIBUTIONS
# ============================================================

print_section("14. TARGET DISTRIBUTIONS")

for target in TARGET_COLUMNS:

    print(f"\n{target}")
    print("-" * 50)

    print(
        merged[target]
        .value_counts(dropna=False)
        .sort_index()
        .to_string()
    )


# ============================================================
# 15. TARGET RANGE CHECK
# ============================================================

print_section("15. TARGET RANGE CHECK")

return_targets = [
    "Target_Return_1D",
    "Target_Return_5D",
    "Target_Return_10D",
]

for target in return_targets:

    if target in merged.columns:

        print(
            f"\n{target}:"
        )

        print(
            f"Min : {merged[target].min():.6f}"
        )

        print(
            f"Mean: {merged[target].mean():.6f}"
        )

        print(
            f"Max : {merged[target].max():.6f}"
        )


# ============================================================
# 16. NEWS COVERAGE
# ============================================================

print_section("16. NEWS COVERAGE")

if "Has_News" in merged.columns:

    news_days = int(
        (merged["Has_News"] == 1).sum()
    )

    coverage = (
        news_days / len(merged) * 100
    )

    print(f"Total rows : {len(merged)}")
    print(f"News days  : {news_days}")
    print(f"Coverage   : {coverage:.2f}%")

if "News_Count" in merged.columns:

    print(
        f"Average news count: "
        f"{merged['News_Count'].mean():.4f}"
    )

if "News_Sentiment" in merged.columns:

    print(
        f"Average sentiment: "
        f"{merged['News_Sentiment'].mean():.6f}"
    )


# ============================================================
# 17. LEAKAGE PROTECTION CHECK
# ============================================================

print_section("17. TARGET LEAKAGE PROTECTION")

suspicious_features = []

target_keywords = [
    "target",
    "future",
    "forward",
    "next_return",
    "future_return",
]

for feature in feature_columns:

    name = feature.lower()

    for keyword in target_keywords:

        if keyword in name:
            suspicious_features.append(feature)
            break

suspicious_features = sorted(
    set(suspicious_features)
)

if suspicious_features:

    print(
        "WARNING: Potentially suspicious "
        "feature names detected:"
    )

    for col in suspicious_features:
        print(f" - {col}")

    fail(
        "Potential target leakage detected. "
        "Inspect these columns before training."
    )

print("PASS: No suspicious target-like feature names.")


# ============================================================
# 18. FINAL COLUMN ORDER
# ============================================================

print_section("18. FINAL DATASET STRUCTURE")

final_columns = (
    [DATE_COL]
    + feature_columns
    + TARGET_COLUMNS
)

merged = merged[final_columns]

print(
    f"Final rows    : {len(merged)}"
)

print(
    f"Final columns : {len(merged.columns)}"
)

print(
    f"Features      : {len(feature_columns)}"
)

print(
    f"Targets       : {len(TARGET_COLUMNS)}"
)


# ============================================================
# 19. FINAL DATE RANGE
# ============================================================

print(
    f"\nDate range:"
)

print(
    f"{merged[DATE_COL].min().date()} "
    f"to "
    f"{merged[DATE_COL].max().date()}"
)


# ============================================================
# 20. SAVE
# ============================================================

print_section("19. SAVING DATASET")

os.makedirs(
    os.path.dirname(OUTPUT_FILE),
    exist_ok=True
)

merged.to_csv(
    OUTPUT_FILE,
    index=False
)

print(
    f"Saved: {OUTPUT_FILE}"
)


# ============================================================
# 21. RELOAD VERIFICATION
# ============================================================

print_section("20. OUTPUT VERIFICATION")

check = pd.read_csv(
    OUTPUT_FILE
)

check[DATE_COL] = pd.to_datetime(
    check[DATE_COL]
)

print(
    f"Reloaded rows    : {len(check)}"
)

print(
    f"Reloaded columns : {len(check.columns)}"
)

print(
    f"Date range       : "
    f"{check[DATE_COL].min().date()} "
    f"to "
    f"{check[DATE_COL].max().date()}"
)

print(
    f"Duplicate dates  : "
    f"{check[DATE_COL].duplicated().sum()}"
)

print(
    f"Missing values   : "
    f"{check.isna().sum().sum()}"
)


# ============================================================
# FINAL CHECK
# ============================================================

if len(check) != len(merged):
    fail("Reloaded dataset row count does not match.")

if check[DATE_COL].duplicated().sum() != 0:
    fail("Duplicate dates found after saving.")

if check.isna().sum().sum() != 0:
    fail("Missing values found after saving.")

print_section("FINAL STATUS")

print("PASS: V2 ML DATASET CREATED SUCCESSFULLY")
print()
print(f"Output: {OUTPUT_FILE}")
print(f"Rows  : {len(check)}")
print(f"Cols  : {len(check.columns)}")
print(
    f"Date  : {check[DATE_COL].min().date()} "
    f"to "
    f"{check[DATE_COL].max().date()}"
)
print()
print("Next step:")
print("Run the V2 time-series split and leakage audit.")
print("=" * 70)